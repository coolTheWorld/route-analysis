def test_the_centreline_condition_ignores_pins_and_offsets():
    """Nothing can be pinned on the centreline; whatever is passed in must change nothing."""

    inputs = _inputs(scenario=Scenario.CORNER)
    plain = solve_scenario(inputs, RoadDimensions())
    noisy = solve_scenario(
        inputs,
        RoadDimensions(),
        Offsets(ea=0.3, eb=-0.2),
        Pins(dims=frozenset({"wa"}), offsets=frozenset({"ea"})),
    )
