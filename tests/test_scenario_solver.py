PROTOTYPE_END_WALL = 0.15
"""What the prototype reports when its artificial end wall binds: a fixed 0.15 m trim."""

PROTOTYPE_INDEPENDENCE = """夹具的独立性对场景而言并不一致，这一点值得写明。

原型是设计交付稿先写的，Python 由它移植而来，所以两边一致证明的是移植忠实。借支路
与双向 U 型两个场景后来按需求方的确认改了机动，原型随之同步 —— 那两处的机动形状因此
不再是独立佐证，等于同一份理解写了两遍。

仍然独立的部分是求值链路本身：原型自己算线段间距与点在多边形内，Python 走 shapely 的
向量化接口，两条完全不同的路。区域构造、位姿采样、镜像与净距计算对全部四个场景依旧
是真正的交叉验证。
"""


def _inputs(**overrides) -> ScenarioInputs:
    base = {"dimensions": DIMENSIONS, "radius": 1.60, "threshold": 0.05}
    return ScenarioInputs(**(base | overrides))


def _pareto(**overrides) -> ScenarioInputs:
    return _inputs(condition=Condition.PARETO, **overrides)


def _fixture_cases():
    data = json.loads(FIXTURE.read_text())
    return data["vehicle"], data["cases"]


def _fixture_inputs(case, dimensions: VehicleDimensions, radius: float) -> ScenarioInputs:
    return _inputs(
        scenario=Scenario(case["type"]),
        bidirectional=case["bidir"],
        gear=Gear(case["gear"]),
        dimensions=dimensions,
        radius=radius,
    )


def _fixture_dims(case) -> RoadDimensions:
    return RoadDimensions(
        **{DIMENSION_KEYS[key]: value for key, value in case["dims"].items()}
    )


def _fixture_offsets(case) -> Offsets:
    """The prototype's offsets in the Python sign convention.

    The stub branch offset ``so`` is positive towards the inside of the turn now, like every
    other offset; the prototype that generated the fixture still uses the old sign and has
    not been resynced, so its ``so`` is negated on the way in. The fixture itself is left
    exactly as the prototype wrote it.
    """

    values = {OFFSET_KEYS[key]: value for key, value in case["off"].items()}
    values["so"] = -values["so"]
    return Offsets(**values)


def test_geometry_layer_matches_the_prototype_case_for_case(monkeypatch):
    """Case-for-case cross-check against the prototype: region, path, sampling, mirror, gear.

    With the end-wall padding at zero the region matches the prototype exactly, so every
    case has to agree to the last digit. The padding itself is covered separately by
    ``test_padded_end_walls_only_ever_loosen_the_result``.

    The fixture was generated by the prototype before the stub branch offset ``so`` had its
    sign flipped to "positive towards the inside", so ``_fixture_offsets`` negates it.
    """

    monkeypatch.setattr(scenario_geometry, "CAP_PAD", 0.0)
    vehicle, cases = _fixture_cases()
    dimensions = VehicleDimensions(
        width=vehicle["W"], center_front=vehicle["Lf"], center_rear=vehicle["Lr"]
    )
    compared = 0
    for case in cases:
        inputs = _fixture_inputs(case, dimensions, vehicle["R"])
        steps = Steps(case["arc_step"], case["line_step"])
        actual = evaluate(
            inputs, _fixture_dims(case), _fixture_offsets(case), steps, detail=True
        ).clearance
        assert actual == pytest.approx(case["clearance"], abs=1e-6), case
        compared += 1
    assert compared > 200, "对拍用例太少，夹具可能没重新生成"


def test_padded_end_walls_only_ever_loosen_the_result():
    """Padding the end walls removes a constraint, so clearance can only grow.

    Same sign caveat as the case-for-case check: the prototype's ``so`` is negated on load.
    """

    vehicle, cases = _fixture_cases()
    dimensions = VehicleDimensions(
        width=vehicle["W"], center_front=vehicle["Lf"], center_rear=vehicle["Lr"]
    )
    loosened = 0
    for case in cases:
        inputs = _fixture_inputs(case, dimensions, vehicle["R"])
        actual = evaluate(
            inputs,
            _fixture_dims(case),
            _fixture_offsets(case),
            Steps(case["arc_step"], case["line_step"]),
            detail=True,
        ).clearance
        assert actual >= case["clearance"] - 1e-6, case
        if actual > case["clearance"] + 1e-6:
            loosened += 1
    assert loosened, "没有任何用例被端墙顶住，夹具已经失去回归价值"


def test_the_prototype_end_wall_capped_every_roomy_case():
    """Record what was fixed: give the prototype room and its clearance pins to the trim."""

