    assert pinned.dims.wa == 3.5
    assert pinned.solved_keys == ("wb",)
    assert pinned.solved
    assert pinned.pins == pins
    assert pinned.min_clearance >= inputs.threshold - 1e-3
    assert free.dims.wa < 3.5, "固定值要比极限宽，才谈得上让出空间"
    assert pinned.dims.wb <= free.dims.wb + 2e-3, "进入道更宽，驶出道不必更宽"


