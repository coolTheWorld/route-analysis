def test_stubback_starts_inside_the_branch_and_leaves_along_the_trunk():
    """The maneuver the requirement owner settled on, pinned end to end.

    Nose south inside the branch, one quarter turn in reverse onto the east side of the
    trunk, then forward away west. The shape it replaced never left the trunk at all: both
    of its arcs met on the trunk centreline, so the front axle bottomed out one radius down
    and only the tail ever swung into the branch.
    """

    inputs = _inputs(scenario=Scenario.STUBBACK)
    result = solve_scenario(inputs, RoadDimensions())
    primitives = result.layout.maneuvers[0].primitives
    assert [item.gear for item in primitives] == [Gear.REVERSE, Gear.DRIVE]

    samples = sample_poses(primitives, DIMENSIONS, FINE)
    reach = np.where(samples.gear_is_drive, DIMENSIONS.center_front, -DIMENSIONS.center_front)
    nose_x, nose_y = samples.x + reach * samples.ux, samples.y + reach * samples.uy

    branch_floor = -result.dims.wh / 2 - result.dims.ls
    assert nose_y[0] < -result.dims.wh / 2, "起点车头必须已经在支路里"
    assert nose_y[0] == pytest.approx(samples.y[0] - DIMENSIONS.center_front, abs=1e-6)
    assert nose_y[0] > branch_floor, "车头不能穿出支路尽头"
    assert samples.x[0] == pytest.approx(0.0, abs=1e-6), "起点落在支路中线上"

    assert samples.x[-1] < samples.x[0], "驶出方向朝西"
    assert samples.y[-1] == pytest.approx(0.0, abs=1e-6), "终点回到主路中线"
    assert nose_x[-1] < samples.x[-1], "终点车头朝西"
    assert bool(samples.gear_is_drive[-1])

    turned = max(samples.x[: len(samples) // 2])
    assert turned > 0, "倒车转弯经过主路东侧"


def test_the_stub_branch_runs_on_and_its_depth_is_not_a_dimension():
    """A stub road carries on past the parked truck, so how much deeper is nobody's limit.

    It used to be solved for, back when the maneuver turned around inside the branch. The
    truck now only starts there, and its nose reaching further in costs nothing.
    """

    assert "ls" not in SOLVED_KEYS[Scenario.STUBBACK]
    result = solve_scenario(_inputs(scenario=Scenario.STUBBACK), RoadDimensions())
    floor = min(point[1] for point in result.layout.region)
    nose = result.layout.maneuvers[0].primitives[0]
    start_y = nose.centre[1] + nose.radius * math.sin(nose.start_angle)
    assert floor < start_y - DIMENSIONS.center_front - 2.0, "支路尽头必须远到够不着"


def test_the_trunk_reach_matches_the_closed_form_and_survives_the_mirror():
    """出弯主路深度 = R + 中心后距 - 支路宽/2 + 阈值, measured from the far wall of the mouth.

    The widest reverse pose is the one where the wheels come straight: the body is then
    along the trunk with its tail a full 中心后距 past the turn centre. Two-way mirrors that
    maneuver, so the reading must not change -- and it cannot be walled in and searched for,
    because the mirrored maneuver drives away through the side the other one swings into.
    """

    for bidirectional in (False, True):
        inputs = _inputs(scenario=Scenario.STUBBACK, bidirectional=bidirectional)
        result = solve_scenario(inputs, RoadDimensions())
        assert result.trunk_reach is not None
        expected = (
            inputs.radius
            + DIMENSIONS.center_rear
            - result.dims.wv / 2
            + inputs.threshold
        )
        assert result.trunk_reach == pytest.approx(expected, abs=2e-3), bidirectional

    other = solve_scenario(_inputs(scenario=Scenario.CORNER), RoadDimensions())
    assert other.trunk_reach is None, "只有借支路那个场景有这项"
