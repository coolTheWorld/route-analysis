@pytest.mark.parametrize(
    ("scenario", "bidirectional", "condition"),
    [
        (Scenario.CORNER, False, Condition.CENTRELINE),
        (Scenario.CORNER, True, Condition.PARETO),
        (Scenario.CROSSBACK, False, Condition.CENTRELINE),
        (Scenario.STUBBACK, False, Condition.CENTRELINE),
        (Scenario.UTURN, False, Condition.CENTRELINE),
        (Scenario.UTURN, True, Condition.PARETO),
    ],
)
def test_solved_dimensions_fed_back_in_still_clear_the_threshold(
    scenario, bidirectional, condition
):
    """The headline check: feed a solved road back in and it must still clear the threshold.

    The road and the offsets it was solved with go straight back into the clearance engine.
    Under the Pareto condition the same road is also fed back through ``solve_scenario``
    with every dimension pinned, which is the pure check the operator gets, and its verdict
    has to be a pass.
    """

    inputs = _inputs(scenario=scenario, bidirectional=bidirectional, condition=condition)
    solved = solve_scenario(inputs, RoadDimensions())
    assert not solved.infeasible
    rechecked = evaluate(inputs, solved.dims, solved.offsets, FINE, detail=True)
    assert rechecked.clearance >= inputs.threshold - 1e-6
    if inputs.pareto:
        checked = solve_scenario(inputs, solved.dims, pins=Pins.all_dims(scenario))
        assert checked.solved_keys == ()
        assert checked.min_clearance >= inputs.threshold - 1e-6
        assert checked.status is ClearanceStatus.SAFE


@pytest.mark.parametrize("scenario", list(Scenario))
def test_a_bigger_threshold_never_asks_for_a_smaller_road(scenario):
    previous = None
    for threshold in (0.05, 0.15, 0.30):
        result = solve_scenario(
            _inputs(scenario=scenario, threshold=threshold), RoadDimensions()
        )
        assert not result.infeasible, (scenario, threshold)
        current = [getattr(result.dims, key) for key in SOLVED_KEYS[scenario]]
        if previous is not None:
            assert sum(current) >= sum(previous) - 1e-6
        previous = current


